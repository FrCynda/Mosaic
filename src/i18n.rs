//! `t(key)` resolves a UI string against the active language, falling back to English on a
//! missing key (and to the raw key itself if even English doesn't have it — useful mid-translation).
//! Only English is populated so far; Phase 6 adds the other 9 language tables as more `match` arms
//! in `table()`, and `plural_category()` gains their plural-category rules (Arabic has 6, Russian 3;
//! English's "one"/"other" is the only rule implemented today).

static LANG: std::sync::RwLock<String> = std::sync::RwLock::new(String::new());

pub fn lang() -> String {
    let l = LANG.read().unwrap();
    if l.is_empty() { "en".into() } else { l.clone() }
}

pub fn set_lang(code: &str) {
    *LANG.write().unwrap() = code.to_string();
}

