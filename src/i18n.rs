/// Every language `table()` knows how to route to, English included — used by the smoke test below
/// and available to the language-picker UI.
pub const LANGS: [&str; 17] = ["en", "es", "ar", "pt", "fr", "sw", "ha", "hi", "zh", "ru", "yo", "ig", "am", "zu", "so", "wo", "om"];

/// Resolves `key` in the active language, then English, then the key itself.
pub fn t(key: &str) -> &'static str {
    table(&lang(), key).or_else(|| en(key)).unwrap_or_else(|| Box::leak(key.to_string().into_boxed_str()))
}

/// CLDR plural-category rules (which `item.<category>` key `t_count` looks up), per language.
/// `n` is always a non-negative item count here, never a fraction, so each rule only needs its
/// integer branches.
fn plural_category(lang: &str, count: i64) -> &'static str {
    let n = count.unsigned_abs();
    match lang {
        // zero/one/two/few(3-10)/many(11-99)/other
        "ar" => match n {
            0 => "zero",
            1 => "one",
            2 => "two",
            _ if n % 100 >= 3 && n % 100 <= 10 => "few",
            _ if n % 100 >= 11 && n % 100 <= 99 => "many",
            _ => "other",
        },
        // one (n%10==1 && n%100!=11) / few (n%10 in 2..4 && n%100 not in 12..14) / many
        "ru" => {
            if n % 10 == 1 && n % 100 != 11 {
                "one"
            } else if (2..=4).contains(&(n % 10)) && !(12..=14).contains(&(n % 100)) {
                "few"
            } else {
                "many"
            }
        }
        // French/Portuguese-BR: 0 and 1 both read as singular ("0 fichier", "0 arquivo")
        "fr" | "pt" => {
            if n <= 1 {
                "one"
            } else {
                "other"
            }
        }
        // Chinese/Yoruba/Igbo/Wolof have no grammatical number
        "zh" | "yo" | "ig" | "wo" => "other",
        // Amharic/Zulu: 0 and 1 both read as singular
        "am" | "zu" => {
            if n <= 1 {
                "one"
            } else {
                "other"
            }
        }
        _ => {
            if n == 1 {
                "one"
            } else {
                "other"
            }
        }
    }
}

/// Like `t_plural`, but substitutes `display` (e.g. a locale-formatted number) for `{n}` instead
/// of the raw count.
pub fn t_count(key: &str, count: i64, display: &str) -> String {
    let cat = plural_category(&lang(), count);
    t(&format!("{key}.{cat}")).replace("{n}", display)
}

/// `t("item", 3)` looks up `"item.other"` and substitutes `{n}`.
pub fn t_plural(key: &str, count: i64) -> String {
    t_count(key, count, &count.to_string())
}

